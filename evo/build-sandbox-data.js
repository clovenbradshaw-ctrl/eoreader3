/* ============================================================
   evo/build-sandbox-data.js — bake the sandbox's data into a browser
   global. Reads the fixtures, the committed golden, and the parity
   harness docs (VOSS / big / the query+answer battery) and writes
   evo/sandbox-data.js → window.EVO_SANDBOX_DATA. Regenerate whenever the
   fixtures or golden change:  node evo/build-sandbox-data.js
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');
const { VOSS, makeBigDoc } = require('../tests/harness');

const ROOT = path.resolve(__dirname, '..');
const FX = path.join(__dirname, 'fixtures');

// the exact query / answer battery tests/parity.js snapshots
const QUERIES = ['who is in this story', 'summarize this', 'what did the keeper say about the boat',
  'what does Marlow want', 'boat to the mainland', 'the storm on the seaward side',
  'What did Zorthax say?', 'thanks that really helps', 'tell me a joke',
  'where is Voss Point', 'who argued about the boat', 'lamp at midnight'];
const ANSWERS = ['Edith set the kettle down and listened.',
  'The keeper said no one could row to the mainland tonight.',
  'Sefton wanted to reach Marlow on the mainland.',
  'The spaceship departed for Jupiter at dawn.'];

function loadFixtures(kind) {
  const dir = path.join(FX, kind);
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().map(f => {
    const fx = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    if (!fx.doc && fx.docFile) fx.doc = fs.readFileSync(path.join(dir, fx.docFile), 'utf8');
    delete fx.docFile;
    return fx;
  });
}

const data = {
  weights: (() => { try { return JSON.parse(fs.readFileSync(path.join(__dirname, 'config.json'), 'utf8')).weights; } catch (e) { return undefined; } })(),
  fixtures: { binding: loadFixtures('binding'), stalls: loadFixtures('stalls'), integration: loadFixtures('integration') },
  golden: JSON.parse(fs.readFileSync(path.join(ROOT, 'tests', 'golden.json'), 'utf8')),
  harness: { VOSS, BIG: makeBigDoc(60), QUERIES, ANSWERS },
};

const out = path.join(__dirname, 'sandbox-data.js');
fs.writeFileSync(out,
  '/* GENERATED by evo/build-sandbox-data.js — do not edit by hand.\n' +
  '   Fixtures + committed golden + parity harness docs for the in-browser sandbox. */\n' +
  '(function (g) { g.EVO_SANDBOX_DATA = ' + JSON.stringify(data) + '; })(typeof window !== "undefined" ? window : globalThis);\n');

const kb = (fs.statSync(out).size / 1024).toFixed(0);
console.log('✓ wrote ' + path.relative(ROOT, out) + ' (' + kb + ' KB) — ' +
  data.fixtures.binding.length + ' binding, ' + data.fixtures.stalls.length + ' stall, ' +
  data.fixtures.integration.length + ' integration fixtures; golden + harness baked in.');
